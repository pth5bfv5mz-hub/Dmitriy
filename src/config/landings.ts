/**
 * ============================================================================
 *  ПОСАДОЧНЫЕ СТРАНИЦЫ ПОД ГРУППЫ ЯНДЕКС ДИРЕКТА
 * ============================================================================
 *  Одна группа объявлений → один объект в этом массиве → одна страница
 *  /<slug>/ со своим H1, title, description, оффером, ценой, формой и FAQ.
 *
 *  Смысл в релевантности: человек искал «сдать медь дорого», кликнул по
 *  объявлению и должен увидеть слово «медь» в заголовке и цену на медь —
 *  а не общий текст про металлолом. Это напрямую влияет и на конверсию,
 *  и на показатель качества в Директе, то есть на цену клика.
 *
 *  ДОБАВИТЬ НОВУЮ СТРАНИЦУ = добавить объект в массив. Роут, sitemap.xml,
 *  метатеги, микроразметка и перелинковка подхватятся автоматически.
 *
 *  ⚠️ Не плодите страницы ради ключей. Страница нужна тогда, когда у группы
 *  свой оффер и своя цена. Иначе она только размывает бюджет.
 * ============================================================================
 */

export interface Landing {
  /** URL: /<slug>/ */
  slug: string;
  /** H1 — единственный на странице. Должен содержать ключ группы. */
  h1: string;
  /** <title>. До ~60 символов, ключ ближе к началу. */
  title: string;
  /** <meta description>. 140–170 символов, с ценой и призывом. */
  description: string;
  /** Подзаголовок под H1 — сам оффер, ради которого кликнули. */
  offer: string;
  /**
   * id категории из prices.ts — цена и сорта подтягиваются оттуда.
   * Пусто — страница услуги без привязки к одному металлу.
   */
  metalId?: string;
  /** 3–4 коротких буллита под оффером. Только конкретика. */
  bullets: string[];
  /** Тег FAQ из faq.ts */
  faqTag: string;
  /** Текст главной кнопки. */
  ctaLabel: string;
  /** Заголовок и текст вводного блока — пишем по-человечески. */
  intro: { title: string; text: string };
  /** Какие категории показать в блоке «что ещё принимаем». Пусто — все. */
  relatedMetalIds?: string[];
  /** Приоритет в sitemap.xml, 0.1–1.0 */
  priority: number;
}

