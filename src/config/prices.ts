/** Форматирование числа в русском стиле: 1 200 */
export function formatNumber(value: number): string {
  return new Intl.NumberFormat("ru-RU").format(Math.round(value));
}

/** «17 – 26 ₽/кг» либо «830 ₽/кг», если границы совпали. */
export function formatRange(from: number, to: number): string {
  if (from === to) return `${formatNumber(from)} ${currency}/кг`;
  return `${formatNumber(from)} – ${formatNumber(to)} ${currency}/кг`;
}

/** Дата прайса по-русски: «16 августа 2026». */
export function formatPriceDate(iso: string = priceUpdatedAt): string {
  return new Intl.DateTimeFormat("ru-RU", { day: "numeric", month: "long", year: "numeric" }).format(
    new Date(`${iso}T00:00:00`),
  );
}

