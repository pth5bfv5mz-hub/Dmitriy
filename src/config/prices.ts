export type MetalGroup = "ferrous" | "nonferrous" | "service";

export interface MetalGrade {
  /** Название сорта: «блеск», «кусковая», «3А» */
  name: string;
  /** Цена за кг, ₽ */
  price: number;
  /** Что это такое простыми словами */
  note?: string;
}

export interface MetalCategory {
  /** Технический id, он же ключ в калькуляторе */
  id: string;
  /** Название для человека */
  name: string;
  group: MetalGroup;
  /** Нижняя граница цены, ₽/кг */
  priceFrom: number;
  /** Верхняя граница цены, ₽/кг */
  priceTo: number;
  /** Короткое описание для карточки */
  short: string;
  /** Что конкретно принимаем — примеры предметов */
  examples: string[];
  /** Сорта внутри категории (показываются на странице категории) */
  grades: MetalGrade[];
  /** Slug посадочной страницы, если она есть (см. landings.ts) */
  landing?: string;
  /** Показывать ли в калькуляторе */
  inCalculator: boolean;
}

