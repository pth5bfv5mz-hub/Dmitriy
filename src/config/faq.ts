/** Вопросы для страницы по тегу, general всегда включается. */
export function faqForTag(tag: string, limit = 8): FaqItem[] {
  const specific = faqItems.filter((i) => i.tags.includes(tag) && tag !== "general");
  const general = faqItems.filter((i) => i.tags.includes("general") && !specific.includes(i));
  return [...specific, ...general].slice(0, limit);
}
